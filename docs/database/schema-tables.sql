-- ============================================================================
-- EduCore — PostgreSQL 16 Schema (documentation form)
-- Target: 49 domain tables (business schema), plus 8 Laravel framework tables.
-- This is the DESCRIPTION-OF-RECORD for the designed schema. Implement via
-- Laravel migrations (see migration-strategy.md), not by running this file.
-- Conventions: see database-conventions.md. Relationships: see
-- relationships.md and skills/academic-domain/SKILL.md.
--
-- APPROVED EQUIVALENCES vs the Laravel migrations (verified 2026-09-25):
--   * PK: IDENTITY here vs bigserial (`$table->id()` with nextval) in the
--     migrations. Both auto-increment; both allow explicit id inserts.
--   * Timestamps: precision 6 + DEFAULT now() here vs precision 0 +
--     CURRENT_TIMESTAMP in the migrations. Equivalent for app writes
--     (application code never emits microseconds).
--   * `uq_gpa_records` (UNIQUE NULLS NOT DISTINCT) is a table CONSTRAINT here
--     but a unique INDEX in the migrations. Identical enforcement.
--   * users.email unique constraint is named `uq_users_email` here but
--     `users_email_unique` in the migrations (scaffold default).
--   * Numeric/smallint defaults differ only in catalog notation
--     (e.g. '100'::numeric vs 100); values identical.
--   The 49-domain/70-FK/57-CHECK/54+3-index structural surface matches exactly.
-- ============================================================================

