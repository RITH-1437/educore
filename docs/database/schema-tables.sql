CREATE TABLE academic_years (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    start_date  DATE NOT NULL,
    end_date    DATE NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'planned',
    is_current  BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_academic_years_code UNIQUE (code),
    CONSTRAINT ck_academic_years_status
        CHECK (status IN ('planned', 'active', 'completed')),
    CONSTRAINT ck_academic_years_range CHECK (start_date < end_date)
);

CREATE TABLE semesters (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT NOT NULL,
    name             VARCHAR(50) NOT NULL,
    code             VARCHAR(20) NOT NULL,
    sequence         SMALLINT NOT NULL,
    start_date       DATE,
    end_date         DATE,
    enrollment_start DATE,
    enrollment_end   DATE,
    exam_start       DATE,
    exam_end         DATE,
    status           VARCHAR(20) NOT NULL DEFAULT 'planned',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_semesters_year_sequence UNIQUE (academic_year_id, sequence),
    CONSTRAINT ck_semesters_status
        CHECK (status IN ('planned', 'open', 'closed', 'completed')),
    CONSTRAINT ck_semesters_range CHECK (start_date IS NULL OR end_date IS NULL OR start_date <= end_date),
    CONSTRAINT fk_semesters_year FOREIGN KEY (academic_year_id)
        REFERENCES academic_years (id) ON DELETE RESTRICT
);

CREATE INDEX idx_semesters_academic_year ON semesters (academic_year_id);

CREATE TABLE courses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT       NOT NULL,
    code          VARCHAR(20)  NOT NULL,
    name          VARCHAR(255) NOT NULL,
    credits       NUMERIC(4,2) NOT NULL,
